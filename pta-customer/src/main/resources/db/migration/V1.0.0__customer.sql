CREATE TABLE customer
(
  id NUMERIC,
  logicalId UUID,
  salutation VARCHAR(20),
  firstName VARCHAR(30),
  lastName VARCHAR(20),
  birth DATE,
  gender VARCHAR(10),
  streetNo VARCHAR(50),
  zip VARCHAR(15),
  city VARCHAR(20),
  region VARCHAR(20),
  country VARCHAR(20),
  email VARCHAR(30),
  phone VARCHAR(20)
);
